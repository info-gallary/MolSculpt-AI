SCALE = 50 / 1.5  # RDKit depictions use 1.5 Å bonds


def entry(cat, name, smiles, note):
    mol = Chem.MolFromSmiles(smiles)
    rdDepictor.Compute2DCoords(mol)
    Chem.Kekulize(mol, clearAromaticFlags=True)
    conf = mol.GetConformer()
    atoms = []
    for a in mol.GetAtoms():
        p = conf.GetAtomPosition(a.GetIdx())
        atoms.append([a.GetSymbol(), round(p.x * SCALE, 1), round(-p.y * SCALE, 1), a.GetFormalCharge()])
    bonds = [[b.GetBeginAtomIdx(), b.GetEndAtomIdx(), int(b.GetBondTypeAsDouble())] for b in mol.GetBonds()]
    return {"category": cat, "name": name, "smiles": smiles, "note": note, "atoms": atoms, "bonds": bonds}


def main():
    data = [entry(*row) for row in LIBRARY]
    js = (
        "// Generated by tools/make_templates.py from RDKit 2D depictions. Do not edit by hand.\n"
        "// atoms: [element, x, y, formal charge]; bonds: [atom index, atom index, order]\n"
        f"export const TEMPLATES = {json.dumps(data, separators=(',', ':'))};\n"
    )
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write(js)
    print(f"{len(data)} templates written")


if __name__ == "__main__":
    main()
